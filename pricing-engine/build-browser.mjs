#!/usr/bin/env node
/**
 * Build the Mini App browser bundle of the pricing engine:
 *   pricing-engine/src/browser.js -> miniapp/vendor/pricing-engine.js
 * (IIFE, minified; tools/build_miniapp_bundle.py inlines it into
 * dist/index.html before app.js.)
 *
 * Usage:  cd pricing-engine && npm run build:browser
 */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const outfile = path.join(here, '..', 'miniapp', 'vendor', 'pricing-engine.js');

await build({
  entryPoints: [path.join(here, 'src', 'browser.js')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  outfile,
  banner: {
    js: '/* Nova Shop Pricing Engine (Dinero.js + Decimal.js) — GENERATED by pricing-engine/build-browser.mjs. Do not edit; source in pricing-engine/src/. */',
  },
});
console.log(`built ${outfile}`);
